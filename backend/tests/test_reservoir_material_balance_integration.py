import pytest
from app.services.reservoir.material_balance import MaterialBalanceEngine, MaterialBalanceHistoryPoint
from app.services.reservoir.contracts import EngineeringStatus


def test_canonical_material_balance_time_series_integration():
    """
    Section 40 Verification:
    - Time-series dataset passed to canonical MBE calculate_history_series.
    - F is generated by canonical MBE.
    - Et is generated by canonical MBE.
    - Linear regression of F vs Et yields slope N and R2.
    - Bo, Bg, Rs are computed from canonical PVTEngine (no manual Bg).
    - No hardcoded N is introduced.
    - No second MBE implementation exists.
    """
    # 4 historical pressure surveys under depletion drive (pi = 4500 psia)
    history = [
        MaterialBalanceHistoryPoint(
            pressure_psia=4300.0,
            np_stb=200000.0,
            wp_stb=10000.0,
            gp_mscf=140000.0
        ),
        MaterialBalanceHistoryPoint(
            pressure_psia=4100.0,
            np_stb=450000.0,
            wp_stb=25000.0,
            gp_mscf=330000.0
        ),
        MaterialBalanceHistoryPoint(
            pressure_psia=3900.0,
            np_stb=750000.0,
            wp_stb=45000.0,
            gp_mscf=580000.0
        ),
        MaterialBalanceHistoryPoint(
            pressure_psia=3700.0,
            np_stb=1100000.0,
            wp_stb=70000.0,
            gp_mscf=900000.0
        )
    ]

    # Invoke canonical MBE using canonical PVT parameters (T=200°F, gas_gravity=0.72, oil_api=38.0)
    # Notice: Bo, Bg, and Rs are NOT manually supplied for the points; they are computed by canonical PVTEngine!
    res = MaterialBalanceEngine.calculate_history_series(
        history=history,
        initial_pressure_psia=4500.0,
        reservoir_temperature_f=200.0,
        gas_gravity=0.72,
        oil_api=38.0
    )

    assert res.status == EngineeringStatus.VALID.value
    val = res.value
    # Estimated OOIP N (stb) returned from regression
    assert val["estimated_ooip_N_stb"] is not None
    assert val["estimated_ooip_N_stb"] > 0
    # R2 returned and statistically valid
    assert val["regression_r2"] is not None
    assert 0.0 <= val["regression_r2"] <= 1.0
    assert val["surveys_analyzed"] == 4

    # Verify that F and Et were generated for each survey point
    pts = res.evidence["survey_points"]
    assert len(pts) == 4
    for pt in pts:
        assert "F_underground_withdrawal_rb" in pt
        assert "Et_total_expansion_rb_stb" in pt
        assert pt["F_underground_withdrawal_rb"] > 0
        assert pt["Et_total_expansion_rb_stb"] > 0
        # Canonical PVT values were populated
        assert pt["bo_rb_stb"] is not None
        assert pt["bg_rb_scf"] is not None
        assert pt["rs_scf_stb"] is not None
